#!/usr/bin/env python3
"""Rebuild the self-hosted WOFF2 fonts in static/fonts/doors/ from Google's sources.

Run: python3 scripts/rebrand/build_fonts.py <dir-with-source-ttfs> static/fonts/doors

     python3 scripts/rebrand/build_fonts.py --icons <dir-with-font-awesome-files> static/fonts/doors assets/css/doors/icons.css

Needs `pip install fonttools brotli`. Sources are the OFL files in github.com/google/fonts
(ofl/newsreader, ofl/sourcesans3). Keeps Latin and Latin Extended-A, which cover every letter in
the site's English, German and Turkish; Arabic and Chinese use system fonts (decision D18). Other
scripts fall back to system fonts, as they did with the wider subset. Newsreader is only ever set
at weight 500, so it keeps only its optical-size axis.

--icons takes fa-solid-900.woff2, fa-brands-400.woff2, fa-regular-400.woff2 and all.min.css from
Font Awesome Free 6.7.2 (cdnjs) and subsets them to the icons in ICONS. Pages download an icon font
only if they show one of its icons. check_design.py fails if a build uses an icon not listed here.
"""

import os
import re
import sys

from fontTools import subset
from fontTools.ttLib import TTFont
from fontTools.varLib import instancer

UNICODES = (
    "U+0000-017F,U+0218-021B,U+0259,U+02BB-02BC,U+02C6,U+02DA,U+02DC,U+0300-0308,U+030A-030C,"
    "U+0327-0328,U+2000-206F,U+20AC,U+2113,U+2122,U+2190-2193,U+2212,U+2248,U+2260,U+2264-2265,U+FFFD"
)
FONTS = [
    # source, axis limits, output
    ("Newsreader[opsz,wght].ttf", {"wght": 500, "opsz": (16, 72)}, "newsreader-var.woff2"),
    ("SourceSans3[wght].ttf", {"wght": (400, 700)}, "source-sans-3-var.woff2"),
    # Only reference lists use italics (decision D15), and those are in the text face.
    ("SourceSans3-Italic[wght].ttf", {"wght": 400}, "source-sans-3-italic.woff2"),
]


# Every Font Awesome icon in templates and content, by style. Keep sorted.
ICONS = {
    "brands": ["bluesky", "facebook", "github", "instagram", "linkedin", "mastodon", "orcid",
               "slack", "twitter", "youtube"],
    "solid": ["angle-right", "arrow-alt-circle-right", "arrow-right", "arrow-up", "bars", "book", "book-open",
              "brain", "chart-line", "chevron-down", "chevron-right", "envelope", "external-link-alt",
              "file-alt", "file-pdf", "flask", "folder", "globe", "graduation-cap", "heart", "layer-group",
              "lightbulb", "link", "play", "project-diagram", "redo", "search", "share-alt", "star", "times",
              "times-circle", "user", "users"],
    "regular": ["envelope", "file-alt", "folder", "user"],
}
ICON_FILES = {"brands": "fa-brands-400.woff2", "solid": "fa-solid-900.woff2", "regular": "fa-regular-400.woff2"}
ICON_STYLES = {
    "brands": (".fab,.fa-brands", 400),
    "solid": (".fa,.fas,.fa-solid", 900),
    "regular": (".far,.fa-regular", 400),
}


def build_icons(source, output, css_path):
    sheet = open(os.path.join(source, "all.min.css"), encoding="utf-8").read()
    code = {}
    for match in re.finditer(r'((?:\.fa-[a-z0-9-]+,?)+)\{--fa:"\\([0-9a-f]+)', sheet):
        for name in re.findall(r"\.fa-([a-z0-9-]+)", match.group(1)):
            code[name] = match.group(2)
    lines = [
        "/* Generated by scripts/rebrand/build_fonts.py --icons: Font Awesome Free 6.7.2 (fonts OFL 1.1,",
        "   code MIT), subset to the icons the site uses. */",
    ]
    bases = []
    for style, names in ICONS.items():
        font = TTFont(os.path.join(source, ICON_FILES[style]))
        options = subset.Options()
        options.flavor = "woff2"
        options.layout_features = []
        subsetter = subset.Subsetter(options)
        subsetter.populate(unicodes=[int(code[name], 16) for name in names])
        subsetter.subset(font)
        font.flavor = "woff2"
        font.save(os.path.join(output, f"icons-{style}.woff2"))
        selector, weight = ICON_STYLES[style]
        lines.append(f"@font-face{{font-family:'Doors Icons {style}';src:url(../fonts/doors/icons-{style}.woff2) format('woff2');font-weight:{weight};font-display:block}}")
        lines.append(f"{selector}{{font-family:'Doors Icons {style}';font-weight:{weight}}}")
        bases.append(selector)
    lines.append(f"{','.join(bases)}{{display:inline-block;line-height:1;-webkit-font-smoothing:antialiased;text-rendering:auto}}")
    names = sorted({name for group in ICONS.values() for name in group})
    lines.append("".join(f'.fa-{name}::before{{content:"\\{code[name]}"}}' for name in names))
    with open(css_path, "w", encoding="utf-8") as handle:
        handle.write("\n".join(lines) + "\n")


def build(source, limits, output):
    font = TTFont(source)
    font = instancer.instantiateVariableFont(font, limits)
    # The instancer drops glyphs left with no variation, such as spaces, and the subsetter
    # then fails looking them up.
    if "gvar" in font:
        kept = font["gvar"].variations
        font["gvar"].variations = {
            name: kept[name] if name in kept else [] for name in font.getGlyphOrder()
        }
    options = subset.Options()
    options.flavor = "woff2"
    options.hinting = False
    options.desubroutinize = True
    options.notdef_outline = True
    options.name_IDs = [1, 2, 3, 4, 6, 13, 14]
    subsetter = subset.Subsetter(options)
    subsetter.populate(unicodes=subset.parse_unicodes(UNICODES))
    subsetter.subset(font)
    font.flavor = "woff2"
    font.save(output)
    print(f"{output}: {os.path.getsize(output) / 1000:.0f} KB")


def main():
    if sys.argv[1] == "--icons":
        os.makedirs(sys.argv[3], exist_ok=True)
        build_icons(*sys.argv[2:5])
        return
    source_dir, out_dir = sys.argv[1:3]
    os.makedirs(out_dir, exist_ok=True)
    for source, limits, output in FONTS:
        build(os.path.join(source_dir, source), limits, os.path.join(out_dir, output))


if __name__ == "__main__":
    main()
