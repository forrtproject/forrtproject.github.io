export function arrangeBrickPiles(parts) {
  if (parts.length !== SETTLED_POSES.length) throw new Error('Brick pile poses must be rebaked after changing the castle geometry.');
  for (const part of parts) {
    const pose = SETTLED_POSES[part.index];
    part.staging = new Vector3(...pose.slice(0, 3));
    part.stagedQuaternion = new Quaternion(...pose.slice(3));
  }
  return parts;
}
